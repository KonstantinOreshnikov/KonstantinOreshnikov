/* Real B4 Chromium Academy E2E: multi-step both colors, persistence, parity and promotion. */
"use strict";
const assert=require("node:assert/strict");
const path=require("node:path");
const {chromium}=require("playwright");
(async()=>{
 const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
 const page=await browser.newPage({viewport:{width:1300,height:880}});
 const errors=[];page.on("pageerror",e=>errors.push(e.message));
 let tests=0;
 const base="file://"+path.resolve(__dirname,"../index.html");
 const square=async(s)=>page.locator('button[aria-label^="'+s+' "]').click();
 const move=async(from,to)=>{await square(from);await square(to);};
 try{
  await page.goto(base);
  await page.waitForFunction("window.ChessOdysseyQA && window.ChessOdysseyQA.academy().total===33");
  assert.equal(await page.locator("#lesson option").count(),34);
  assert.deepEqual(await page.evaluate(()=>window.ChessOdysseyQA.academy().tracks),["basics","tactics","openings","endgames"]);
  tests++;
  await page.selectOption("#academy-track","tactics");
  assert.equal(await page.locator("#lesson option:not([hidden])").count(),9);
  await page.selectOption("#lesson","fork");
  assert.match(await page.locator("#academy-intro").innerText(),/Конь/);
  assert.equal(await page.evaluate(()=>window.ChessOdysseyQA.academy().active),"fork");
  tests++;
  // Incorrect legal target must not mutate the training position or award credit.
  await move("b5","d4");
  assert.match(await page.locator("#lesson-status").innerText(),/не решение/);
  assert.equal(await page.locator("#completed").innerText(),"0/33");
  assert.equal(await page.evaluate(()=>window.ChessOdysseyQA.academy().step),0);
  tests++;
  await move("b5","c7");
  assert.equal(await page.locator("#completed").innerText(),"1/33");
  assert.equal(await page.locator("#next-lesson").isVisible(),true);
  tests++;
  await page.locator("#next-lesson").click();
  assert.equal(await page.evaluate(()=>window.ChessOdysseyQA.academy().active),"pin");
  await page.locator("#resume-game").click();
  assert.equal(await page.locator("#moves").innerText(),"—");
  tests++;
  // Three-stage Black opening, with automatically scripted White replies.
  await page.selectOption("#academy-track","openings");
  await page.selectOption("#lesson","sicilian");
  assert.equal(await page.locator("#side").inputValue(),"b");
  assert.equal(await page.evaluate(()=>window.ChessOdysseyQA.academy().step),0);
  await move("c7","c5");
  assert.match(await page.locator("#moves").innerText(),/c5 Nf3/);
  assert.equal(await page.evaluate(()=>window.ChessOdysseyQA.academy().step),1);
  tests++;
  // Resume exact stage after reload; original practice PGN stays parked.
  await page.reload();
  await page.waitForFunction("window.ChessOdysseyQA && window.ChessOdysseyQA.academy().active==='sicilian'");
  assert.equal(await page.evaluate(()=>window.ChessOdysseyQA.academy().step),1);
  assert.match(await page.locator("#academy-step").innerText(),/Шаг 2 из 3/);
  tests++;
  await page.selectOption("#lang","en");
  assert.match(await page.locator("#academy-intro").innerText(),/asymmetric/);
  assert.match(await page.locator("#academy-step").innerText(),/Step 2 of 3/);
  await page.selectOption("#lang","az");
  assert.match(await page.locator("#academy-intro").innerText(),/asimmetrik/);
  await page.selectOption("#lang","ru");
  tests++;
  await move("d7","d6");
  assert.match(await page.locator("#moves").innerText(),/d6.*d4/s);
  await move("c5","d4");
  assert.equal(await page.locator("#completed").innerText(),"2/33");
  tests++;
  // Wrong underpromotion is rejected; exact queen promotion is accepted.
  await page.selectOption("#academy-track","basics");
  await page.selectOption("#lesson","promotion");
  await move("a7","a8");
  assert.equal(await page.locator("#promotion").isVisible(),true);
  await page.locator('button[data-promote="n"]').click();
  assert.equal(await page.locator("#promotion").isVisible(),true);
  assert.equal(await page.locator("#completed").innerText(),"2/33");
  await page.locator('button[data-promote="q"]').click();
  assert.equal(await page.locator("#completed").innerText(),"3/33");
  assert.equal(await page.locator('button[aria-label^="a8 w q"]').count(),1);
  tests++;
  // An explicitly taught underpromotion must accept the knight.
  await page.selectOption("#academy-track","endgames");
  await page.selectOption("#lesson","end-underpromotion");
  await move("a7","a8");
  await page.locator('button[data-promote="n"]').click();
  assert.equal(await page.locator("#completed").innerText(),"4/33");
  assert.equal(await page.locator('button[aria-label^="a8 w n"]').count(),1);
  tests++;
  // Three guided White moves with scripted Black replies.
  await page.selectOption("#academy-track","openings");
  await page.selectOption("#lesson","italian");
  await move("e2","e4");
  assert.equal(await page.evaluate(()=>window.ChessOdysseyQA.academy().step),1);
  await move("g1","f3");
  assert.equal(await page.evaluate(()=>window.ChessOdysseyQA.academy().step),2);
  await move("f1","c4");
  assert.equal(await page.locator("#completed").innerText(),"5/33");
  assert.match(await page.locator("#moves").innerText(),/Bc4/);
  tests++;
  await page.locator("#resume-game").click();
  assert.equal(await page.locator("#moves").innerText(),"—");
  assert.equal(await page.evaluate(()=>window.ChessOdysseyQA.academy().active),null);
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem("chess-odyssey-v01")));
  assert.equal(saved.completed.length,5);
  tests++;
  await page.setViewportSize({width:390,height:844});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2);
  assert.equal(overflow,false);
  tests++;
  await page.goto("file://"+path.resolve(__dirname,"../dist/ChessOdyssey_v0.4.0_PREVIEW.html"));
  await page.waitForFunction("window.ChessOdysseyQA && window.ChessOdysseyQA.academy().total===33");
  assert.equal(await page.locator("#lesson option").count(),34);
  await page.selectOption("#academy-track","endgames");
  await page.selectOption("#lesson","end-queenmate");
  assert.equal(await page.locator("#board .square").count(),64);
  tests++;
  assert.deepEqual(errors,[]);
  tests++;
  console.log("PASS B4 Academy real Chromium "+tests+" / "+tests);
 }finally{await browser.close();}
})().catch(error=>{console.error("FAIL B4 Academy Chromium",error);process.exitCode=1;});
